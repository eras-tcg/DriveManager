package com.drive.drive_manager.simulator.engine.cards

import com.drive.drive_manager.simulator.engine.Amount
import com.drive.drive_manager.simulator.engine.CardDefinition
import com.drive.drive_manager.simulator.engine.Condition
import com.drive.drive_manager.simulator.engine.EffectStep
import com.drive.drive_manager.simulator.engine.Reaction
import com.drive.drive_manager.simulator.engine.effects.model.Action
import java.lang.reflect.Modifier
import kotlin.reflect.KClass
import kotlin.reflect.KType
import kotlin.reflect.full.primaryConstructor

/**
 * Writes [CardModelReader] (common code) from the card model's classes, as Jackson saw them with `EffectJson`'s settings:
 *
 * - the registered type ids are the simple names of the members of the families [FAMILIES] (their records and Kotlin
 *   `data object`s, through the sealed hierarchy: `EffectJson.collect`);
 * - a class is typed ("type" names it) when it is one of [TYPED] or a subtype of one, also where a property names it as a
 *   concrete class (a `Replacement`), and then its id must be one of the registered subtypes of the declared type;
 * - a record's fields are its components, read as [JsonFields] says.
 *
 * Run by [CardModelReaderGeneratorTest]: it fails while the checked-in file differs, and rewrites it with
 * `./gradlew jvmTest -PregenerateCardReader`.
 */
object CardModelReaderGenerator {

    /** `EffectJson.mapper()`'s families (registered subtypes). */
    private val FAMILIES: List<KClass<*>> = listOf(EffectStep::class, Action::class, Condition::class, Amount::class, Reaction::class)

    /** `EffectJson.mapper()`'s mix-in targets (`@JsonTypeInfo`). */
    private val TYPED: List<KClass<*>> = FAMILIES + EffectStep.NeedsTarget::class

    const val FILE = "src/commonMain/kotlin/com/drive/drive_manager/simulator/engine/cards/CardModelReader.kt"

    /** Registered (id, class) pairs: an id may name members of different families (`Amount.Gems`, `Action.Gems`). */
    private val registered = LinkedHashSet<Pair<String, KClass<*>>>()
    private val functions = sortedMapOf<String, String>()
    private val pending = ArrayDeque<KClass<*>>()
    private val queued = HashSet<KClass<*>>()

    fun generate(): String {
        registered.clear(); functions.clear(); pending.clear(); queued.clear(); typedBases.clear()
        for (family in FAMILIES) collect(family.java)
        need(CardDefinition::class)
        while (pending.isNotEmpty()) emit(pending.removeFirst())
        val out = StringBuilder()
        out.append(
            """
            |// GENERATED by CardModelReaderGenerator (eras-engine's jvmTest) from the card model's classes. Do not edit: after a
            |// change to the model, run `./gradlew jvmTest -PregenerateCardReader` (CardModelReaderGeneratorTest fails until then).
            |package com.drive.drive_manager.simulator.engine.cards
            |
            |import com.drive.drive_manager.simulator.engine.cards.JsonFields as J
            |import kotlinx.serialization.json.JsonElement
            |import kotlinx.serialization.json.JsonObject
            |
            |/** The card model read from JSON trees, one function per class, as [JsonFields] reads each value. */
            |@Suppress("RedundantSuppression", "FunctionName", "UNUSED_PARAMETER")
            |internal object CardModelReader {
            |
            |    /** The registered type ids (the records' and objects' simple names) of each family. */
            |    private val TYPES: Map<String, List<String>> = mapOf(
            |
            """.trimMargin()
        )
        for (base in typedBases.toSortedMap()) {
            out.append("        \"${base.key}\" to listOf(${base.value.joinToString(", ") { "\"$it\"" }}),\n")
        }
        out.append("    )\n")
        for (f in functions.values) out.append('\n').append(f)
        out.append("}\n")
        return out.toString()
    }

    /** The registered ids a value declared as each typed class may name. */
    private val typedBases = HashMap<String, List<String>>()

    private fun collect(type: Class<*>) {
        if (type.isRecord || kotlinObject(type)) {
            registered.add(type.simpleName to type.kotlin)
            return
        }
        type.permittedSubclasses?.forEach { collect(it) }
    }

    private fun kotlinObject(type: Class<*>): Boolean {
        if (type.isInterface || !Modifier.isFinal(type.modifiers)) return false
        return try {
            type.getField("INSTANCE").type == type
        } catch (_: NoSuchFieldException) {
            false
        }
    }

    private fun typed(k: KClass<*>) = TYPED.any { it.java.isAssignableFrom(k.java) }

    private fun need(k: KClass<*>) {
        if (queued.add(k)) pending.addLast(k)
    }

    private fun name(k: KClass<*>): String {
        val q = k.qualifiedName!!
        val simple = q.removePrefix(k.java.packageName + ".").replace(".", "")
        return simple.replaceFirstChar { it.lowercase() }
    }

    private fun label(k: KClass<*>) = k.qualifiedName!!.removePrefix(k.java.packageName + ".")

    /** The function that reads a value declared as [k], and what it needs. */
    private fun emit(k: KClass<*>) {
        val fn = name(k)
        val q = k.qualifiedName!!
        val java = k.java
        val sb = StringBuilder()
        if (typed(k)) {
            // Jackson's ids for a declared type: the registered subtypes of it
            val members = registered.filter { java.isAssignableFrom(it.second.java) }.groupBy({ it.first }, { it.second })
            for ((id, classes) in members) check(classes.toSet().size == 1) { "$q: two subtypes named $id: $classes" }
            val ids = members.keys.sorted()
            check(ids.isNotEmpty()) { "No registered subtype of $q" }
            typedBases[label(k)] = ids
            sb.append("    fun $fn(e: JsonElement, at: String): $q {\n")
            sb.append("        val o = J.objectOf(e, at, \"${label(k)}\")\n")
            sb.append("        return when (val id = J.typeId(o, at, \"${label(k)}\")) {\n")
            for (id in ids) {
                val member = members.getValue(id).first()
                sb.append("            \"$id\" -> ${record(member)}(o, at)\n")
            }
            sb.append("            else -> J.unknownType(at, id, \"${label(k)}\", TYPES.getValue(\"${label(k)}\"))\n")
            sb.append("        }\n    }\n")
        } else {
            check(java.isRecord) { "Not a record, an object or a typed family: $q" }
            sb.append("    fun $fn(e: JsonElement, at: String): $q = ${record(k)}(J.objectOf(e, at, \"${label(k)}\"), at)\n")
        }
        functions[fn] = sb.toString()
    }

    /** The function that reads the fields of a record or an object (its type already read). */
    private fun record(k: KClass<*>): String {
        val fn = "read" + name(k).replaceFirstChar { it.uppercase() }
        if (functions.containsKey(fn)) return fn
        functions[fn] = ""
        val q = k.qualifiedName!!
        val typed = typed(k)
        val sb = StringBuilder()
        if (k.objectInstance != null) {
            sb.append("    private fun $fn(o: JsonObject, at: String): $q {\n")
            sb.append("        J.fields(o, at, \"${label(k)}\", emptySet(), $typed)\n")
            sb.append("        return $q\n    }\n")
        } else {
            check(k.java.isRecord) { "Not a record: $q" }
            val constructor = k.primaryConstructor ?: error("No primary constructor: $q")
            val components = k.java.recordComponents.map { it.name }
            val params = constructor.parameters
            check(params.map { it.name } == components) { "$q: constructor ${params.map { it.name }} is not the record $components" }
            check(!typed || "type" !in components) { "$q: a typed record with a field \"type\"" }
            sb.append("    private fun $fn(o: JsonObject, at: String): $q {\n")
            sb.append("        J.fields(o, at, \"${label(k)}\", setOf(${components.joinToString(", ") { "\"$it\"" }}), $typed)\n")
            sb.append("        return $q(\n")
            for (p in params) sb.append("            ${p.name} = ${read(p.type, p.name!!, q)},\n")
            sb.append("        )\n    }\n")
        }
        functions[fn] = sb.toString()
        return fn
    }

    /** How a field of type [type] is read from `o`. */
    private fun read(type: KType, key: String, owner: String): String {
        val k = type.classifier as? KClass<*> ?: error("$owner.$key: $type")
        val nullable = type.isMarkedNullable
        fun required(expr: String) = if (nullable) expr else "J.required($expr, at, \"$key\")"
        return when {
            k == Int::class -> if (nullable) "J.intOrNull(o, \"$key\", at)" else "J.int(o, \"$key\", at)"
            k == Boolean::class -> { check(!nullable) { "$owner.$key: Boolean?" }; "J.bool(o, \"$key\", at)" }
            k == String::class -> required("J.str(o, \"$key\", at)")
            k.java.isEnum -> required("J.enum(o, \"$key\", at, ${k.qualifiedName}.entries, \"${label(k)}\")")
            k == List::class || k == Set::class -> {
                val element = type.arguments.single().type ?: error("$owner.$key: $type")
                val call = if (k == List::class) "list" else "set"
                "J.$call(o, \"$key\", at) { e, p -> ${element(element, "$owner.$key")} }"
            }
            else -> {
                need(k)
                required("J.value(o, \"$key\", at, ::${name(k)})")
            }
        }
    }

    private fun element(type: KType, where: String): String {
        val k = type.classifier as? KClass<*> ?: error("$where: $type")
        return when {
            k == String::class -> "J.stringElement(e, p)"
            k == Int::class -> "J.intElement(e, p)"
            k.java.isEnum || k == List::class || k == Set::class || k == Boolean::class -> error("$where: elements of $type")
            else -> { need(k); "${name(k)}(e, p)" }
        }
    }
}
